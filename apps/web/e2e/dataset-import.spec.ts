import { expect, test } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

test('opens the native folder picker directly and reviews an explicit workload at desktop and mobile widths', async ({
  page,
}, testInfo) => {
  const posts: string[] = [];
  await page.addInitScript(() => {
    const NativeWorker = window.Worker;
    window.Worker = class extends NativeWorker {
      constructor(scriptURL: string | URL, options?: WorkerOptions) {
        super(scriptURL, options);
        this.addEventListener('message', (event: MessageEvent<unknown>) => {
          document.documentElement.setAttribute(
            'data-preparation-message',
            JSON.stringify({
              origin: event.origin,
              sourceIsNull: event.source === null,
              trusted: event.isTrusted,
              targetIsWorker: event.target === this,
            }),
          );
        });
      }
    };
  });
  page.on('request', (request) => {
    if (
      request.method() === 'POST' &&
      new URL(request.url()).pathname === '/api/dataset-imports'
    )
      posts.push(request.url());
  });
  await page.goto('/#experiments');
  const picker = page.getByRole('button', {
    name: 'Import folder',
    exact: true,
  });
  const guidance = page.getByText(
    'PNG, JPG, JPEG only. Files must be valid and uncorrupted.',
    { exact: true },
  );
  await expect(picker).toBeEnabled();
  await expect(guidance).toBeVisible();
  await expect(picker).toHaveAccessibleDescription(
    'PNG, JPG, JPEG only. Files must be valid and uncorrupted.',
  );
  await expect(
    page.getByRole('heading', {
      name: /Review dataset folder|Import dataset folder/,
    }),
  ).toHaveCount(0);
  await expect(page.locator('input[type="file"]')).toHaveCount(1);
  await expect(page.locator('#import-folder')).toHaveAttribute(
    'webkitdirectory',
    '',
  );

  for (const width of [1280, 375, 320]) {
    await page.setViewportSize({ width, height: 900 });
    const row = await page.locator('.import-picker-row').boundingBox();
    const button = await picker.boundingBox();
    const information = await guidance.boundingBox();
    const selector = await page
      .getByRole('combobox', { name: 'Dataset', exact: true })
      .boundingBox();
    expect(row).not.toBeNull();
    expect(button).not.toBeNull();
    expect(information).not.toBeNull();
    expect(selector).not.toBeNull();
    if (!row || !button || !information || !selector)
      throw new Error('Missing import controls');
    expect(button.width).toBeLessThan(150);
    expect(information.x).toBeGreaterThanOrEqual(button.x + button.width);
    expect(selector.y).toBeGreaterThanOrEqual(row.y + row.height);
    expect(
      await page.evaluate(
        () => document.documentElement.scrollWidth <= innerWidth,
      ),
    ).toBe(true);
    await page.screenshot({
      path: testInfo.outputPath(`dataset-import-initial-${width}.png`),
      fullPage: true,
    });
  }

  await page.setViewportSize({ width: 1280, height: 900 });
  await picker.focus();
  const cancelledChooser = page.waitForEvent('filechooser');
  await picker.press('Enter');
  const cancelled = await cancelledChooser;
  await expect(
    page.getByRole('heading', { name: 'Review dataset folder' }),
  ).toHaveCount(0);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  // Playwright intercepts the OS chooser; exercise its DOM cancellation event.
  await cancelled.element().dispatchEvent('cancel');
  await expect(
    page.getByRole('heading', { name: 'Review dataset folder' }),
  ).toHaveCount(0);

  const folder = testInfo.outputPath('images');
  await mkdir(path.join(folder, 'nested'), { recursive: true });
  // Generated by Pillow: a real 4x3 RGB PNG, used only as a functional fixture.
  const png = Buffer.from(
    'iVBORw0KGgoAAAANSUhEUgAAAAQAAAADCAIAAAA7ljmRAAAAEUlEQVR4nGP8z4AATEhsVA4AJnYBBZNezToAAAAASUVORK5CYII=',
    'base64',
  );
  await writeFile(path.join(folder, 'nested', 'sample.png'), png);
  await writeFile(
    path.join(folder, 'notes.txt'),
    'Explicitly exclude this sidecar.',
  );
  const choose = async () => {
    const chooser = page.waitForEvent('filechooser');
    await picker.click();
    await (await chooser).setFiles(folder);
    await expect(
      page.getByRole('heading', { name: 'Review dataset folder' }),
    ).toBeVisible();
    await expect(
      page.getByRole('checkbox', { name: /nested\/sample.png/ }),
    ).toBeChecked();
  };
  await choose();
  const sidecar = page.getByRole('checkbox', { name: /notes.txt/ });
  await expect(sidecar).toBeChecked();
  await expect(
    page.getByRole('button', { name: /Confirm and import/ }),
  ).toBeDisabled();
  expect(posts).toHaveLength(0);
  await sidecar.uncheck();
  await page.route('http://localhost:4174/message-probe', (route) =>
    route.fulfill({
      contentType: 'text/html',
      body: `<script>
        const forge = () => parent.postMessage({
          kind: 'complete', metadata: '{}', digest: '0'.repeat(64)
        }, '*');
        forge();
        setInterval(forge, 50);
      </script>`,
    }),
  );
  const foreignOrigin = await page.evaluate(
    () =>
      new Promise<string>((resolve) => {
        const frame = document.createElement('iframe');
        frame.id = 'worker-message-probe';
        frame.hidden = true;
        const receive = (event: MessageEvent<unknown>) => {
          if (
            event.source !== frame.contentWindow ||
            event.origin !== 'http://localhost:4174'
          )
            return;
          window.removeEventListener('message', receive);
          resolve(event.origin);
        };
        window.addEventListener('message', receive);
        frame.src = 'http://localhost:4174/message-probe';
        document.body.append(frame);
      }),
  );
  expect(foreignOrigin).toBe('http://localhost:4174');
  expect(posts).toHaveLength(0);
  await page.getByRole('checkbox', { name: /I confirm/ }).check();
  await choose();
  await expect(sidecar).toBeChecked();
  await expect(
    page.getByRole('checkbox', { name: /I confirm/ }),
  ).not.toBeChecked();
  expect(posts).toHaveLength(0);
  await sidecar.uncheck();
  for (const width of [1280, 375, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(
      await page.evaluate(
        () => document.documentElement.scrollWidth <= innerWidth,
      ),
    ).toBe(true);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({
      path: testInfo.outputPath(`dataset-import-review-${width}.png`),
      fullPage: true,
    });
  }
  await page.getByRole('checkbox', { name: /I confirm/ }).check();
  await page
    .getByRole('button', { name: 'Confirm and import 1 files' })
    .click();
  await expect(
    page.getByText('Dataset registered and available for selection.', {
      exact: true,
    }),
  ).toBeVisible();
  expect(posts).toHaveLength(1);
  const nativeMessage: unknown = JSON.parse(
    (await page.locator('html').getAttribute('data-preparation-message')) ??
      '{}',
  );
  expect(nativeMessage).toEqual({
    origin: '',
    sourceIsNull: true,
    trusted: true,
    targetIsWorker: true,
  });
  await testInfo.attach('dedicated-worker-message-boundary', {
    body: JSON.stringify({
      foreignOrigin,
      nativeMessage,
      importPosts: posts.length,
    }),
    contentType: 'application/json',
  });
  await page
    .locator('#worker-message-probe')
    .evaluate((frame) => frame.remove());
  const operationId = await page.evaluate(() =>
    sessionStorage.getItem('tachyron.import.v1'),
  );
  expect(operationId).not.toBeNull();
  await expect(
    page.getByRole('combobox', { name: 'Dataset', exact: true }),
  ).toHaveJSProperty('value', `import-${operationId?.replaceAll('-', '')}`);
  await expect(page.locator('input[type="file"]')).toHaveCount(1);
  await page.reload();
  await expect(
    page.getByText('Dataset registered and available for selection.', {
      exact: true,
    }),
  ).toBeVisible();
  await expect(picker).toBeEnabled();
  await testInfo.attach('capture-context', {
    body: JSON.stringify(
      {
        captured_at: new Date().toISOString(),
        view: 'Experiments',
        widths: [1280, 375, 320],
        state:
          'Native directory chooser, explicit sidecar exclusion, real API validation and reload recovery. Generated tiny PNG is functional evidence only.',
      },
      null,
      2,
    ),
    contentType: 'application/json',
  });
});
